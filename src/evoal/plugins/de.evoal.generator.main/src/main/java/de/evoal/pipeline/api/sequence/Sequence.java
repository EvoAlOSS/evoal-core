package de.evoal.pipeline.api.sequence;

import de.evoal.languages.model.base.definitions.DataDescription;

import de.evoal.models.core.cdi.EvoalComponent;
import org.eclipse.emf.ecore.EStructuralFeature;

import java.util.Map;

/**
 * A sequence to get data from.
 */
public interface Sequence extends EvoalComponent<Sequence> {

    /**
     * @return The initial value of {@link #getVariable()}.
     */
    public Object getInitialValue();

    /**
     * @return The feature (data) this sequence writes.
     */
    public EStructuralFeature getVariable();

    /**
     * @return The next value.
     */
    Object next();

    /**
     * Sets the symbol table to use. It contains the current value of each feature that
     *   is generated by a sequence of the same generator.
     *
     * @param symbolTable The symbol table.
     * @param features Translation of the data descriptions used in expressions into features.
     */
    public void setSymbolTable(final Map<EStructuralFeature, Object> symbolTable, final Map<DataDescription, EStructuralFeature> features);
}
