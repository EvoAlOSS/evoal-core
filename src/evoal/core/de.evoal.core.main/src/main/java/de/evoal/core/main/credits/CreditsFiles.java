package de.evoal.core.main.credits;

import java.io.IOException;
import java.io.InputStream;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.security.MessageDigest;
import java.security.NoSuchAlgorithmException;
import java.util.ArrayList;
import java.util.HexFormat;
import java.util.List;
import java.util.Locale;
import java.util.Optional;

import tools.jackson.databind.DeserializationFeature;
import tools.jackson.databind.JsonNode;
import tools.jackson.databind.json.JsonMapper;

/**
 * The files that describe the third-party libraries of a module. They lie in the folder
 *   {@value #FOLDER} of the module jar:
 * <ul>
 *   <li>{@value #SBOM_FILE}: the CycloneDX SBOM that the build generates;</li>
 *   <li>{@value #CREDITS_FILE}: the hand-written purpose, licence choice and citations per
 *     shipped library ({@link ModuleCredits}), optional for a module without third-party
 *     libraries;</li>
 *   <li>{@value #CITATIONS_FILE}: the BibTeX entries that the citations name, optional.</li>
 * </ul>
 * core.main also holds the generic licence texts in {@value #LICENSES_FOLDER}, one file
 *   {@code <SPDX id>.txt} per licence.
 */
public final class CreditsFiles {
    /**
     * The BibTeX file with the citations.
     */
    public static final String CITATIONS_FILE = "credits.bib";

    /**
     * The hand-written credits.
     */
    public static final String CREDITS_FILE = "credits.json";

    /**
     * The folder of the files in a module jar.
     */
    public static final String FOLDER = "META-INF/evoal";

    /**
     * The folder of the licence texts in core.main.
     */
    public static final String LICENSES_FOLDER = FOLDER + "/licenses";

    /**
     * Reads the credits file; unknown properties are errors, so a misspelt field is reported.
     */
    private static final JsonMapper MAPPER = JsonMapper.builder()
                                                       .enable(DeserializationFeature.FAIL_ON_UNKNOWN_PROPERTIES)
                                                       .build();

    /**
     * The CycloneDX SBOM generated by the build.
     */
    public static final String SBOM_FILE = "sbom.cdx.json";

    private CreditsFiles() {
    }

    /**
     * @return An unmodifiable copy of the list, an empty list for {@code null}.
     */
    static <T> List<T> copyOrEmpty(final List<T> list) {
        if(list == null) {
            return List.of();
        }

        return List.copyOf(list);
    }

    /**
     * @return The SHA-256 hash of the file in lower-case hexadecimal, as in the SBOM.
     */
    static String hashOf(final Path file) throws IOException {
        final MessageDigest digest;
        try {
            digest = MessageDigest.getInstance("SHA-256");
        } catch(final NoSuchAlgorithmException e) {
            throw new IllegalStateException("The JVM does not support SHA-256.", e);
        }

        final byte[] content = Files.readAllBytes(file);
        final byte[] hash = digest.digest(content);

        return HexFormat.of()
                        .formatHex(hash);
    }

    /**
     * Reads the hand-written credits.
     *
     * @param json The content of {@value #CREDITS_FILE}.
     * @throws tools.jackson.core.JacksonException if the content is not valid.
     */
    public static ModuleCredits readCredits(final String json) {
        return MAPPER.readValue(json, ModuleCredits.class);
    }

    /**
     * Reads the generic text of a licence from core.main.
     *
     * @param licenseId The SPDX id, e.g. {@code Apache-2.0}.
     * @return The text, empty if core.main has none.
     * @throws IOException if the text exists but cannot be read.
     */
    public static Optional<String> readLicenseText(final String licenseId) throws IOException {
        final String resource = "/" + LICENSES_FOLDER + "/" + licenseId + ".txt";

        try(InputStream stream = CreditsFiles.class.getResourceAsStream(resource)) {
            if(stream == null) {
                return Optional.empty();
            }

            final byte[] content = stream.readAllBytes();

            return Optional.of(new String(content, StandardCharsets.UTF_8));
        }
    }

    /**
     * Reads the libraries of a CycloneDX SBOM.
     *
     * @param json The content of {@value #SBOM_FILE}.
     * @throws tools.jackson.core.JacksonException if the content is no JSON.
     */
    public static List<SbomComponent> readSbom(final String json) {
        final JsonNode document = MAPPER.readTree(json);

        return document.path("components")
                       .values()
                       .stream()
                       .map(CreditsFiles::toComponent)
                       .toList();
    }

    /**
     * Reads the module that a CycloneDX SBOM describes ({@code metadata.component}).
     *
     * @param json The content of {@value #SBOM_FILE}.
     * @throws tools.jackson.core.JacksonException if the content is no JSON.
     */
    public static SbomComponent readSbomModule(final String json) {
        final JsonNode document = MAPPER.readTree(json);
        final JsonNode module = document.path("metadata")
                                        .path("component");

        return toComponent(module);
    }

    /**
     * @return The SHA-256 hash of the component, {@code null} if it has none.
     */
    private static String sha256Of(final JsonNode component) {
        return component.path("hashes")
                        .values()
                        .stream()
                        .filter(hash -> hash.path("alg").asString("").equals("SHA-256"))
                        .map(hash -> hash.path("content").asString(""))
                        .map(content -> content.toLowerCase(Locale.ROOT))
                        .findFirst()
                        .orElse(null);
    }

    private static SbomComponent toComponent(final JsonNode component) {
        final List<String> licenseIds = new ArrayList<>();
        final List<String> licenseNames = new ArrayList<>();
        for(final JsonNode choice : component.path("licenses")) {
            final JsonNode license = choice.path("license");
            final String id = license.path("id").asString("");
            final String name = license.path("name").asString("");
            final String expression = choice.path("expression").asString("");

            if(!id.isEmpty()) {
                licenseIds.add(id);
            } else if(!name.isEmpty()) {
                licenseNames.add(name);
            } else if(!expression.isEmpty()) {
                licenseNames.add(expression);
            }
        }

        final String group = component.path("group").asString("");
        final String name = component.path("name").asString("");
        final String version = component.path("version").asString("");
        final String sha256 = sha256Of(component);
        final String website = websiteOf(component);

        return new SbomComponent(group, name, version, licenseIds, licenseNames, sha256, website, component);
    }

    /**
     * @return The project link of the component, {@code null} if it has none.
     */
    private static String websiteOf(final JsonNode component) {
        return component.path("externalReferences")
                        .values()
                        .stream()
                        .filter(reference -> reference.path("type").asString("").equals("website"))
                        .map(reference -> reference.path("url").asString(""))
                        .findFirst()
                        .orElse(null);
    }
}
